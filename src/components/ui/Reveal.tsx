import type { ReactNode } from 'react';
import { motion } from 'framer-motion';

/** Lightweight scroll-reveal used across marketing sections instead of AOS —
 *  keeps animation declarative/typed and avoids a second animation runtime. */
export function Reveal({
  children,
  delay = 0,
  className,
}: {
  children: ReactNode;
  delay?: number;
  className?: string;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 24 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: '-80px' }}
      transition={{ duration: 0.5, delay, ease: 'easeOut' }}
    >
      {children}
    </motion.div>
  );
}
